function normalizePlanetKey(name: string): string {
  return name.toLowerCase().replace(/\s+/g, '');
}

export function lookupFallbackPlanet(planetName: string): FallbackPlanet | null {
  const key = normalizePlanetKey(planetName);
  const aliased = ALIASES[key] || ALIASES[planetName.toLowerCase().trim()] || key;
  return FALLBACK_PLANETS[aliased] ?? null;
}
